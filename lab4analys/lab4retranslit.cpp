// ?????????? ?????? ??? -1
int find_translit(const char *s, const char **table)
{
    for (int i = 0; table[i] != NULL; i++) {
        int len = strlen(table[i]);
        if (strncasecmp(s, table[i], len) == 0) {
            return i;
        }
    }
    return -1;
}

// ??????? ????????? ??????????????: ?????? ??????????? ????? ? ????? ???????
void convert_word(const char *word, FILE *out, int make_upper)
{
    int i = 0;
    int first_char = 1;  // ????: ?????? ????? ????? (??? ?????????)

    while (word[i] != '\0') {
        // ???? ??? ????????? ????? — ???? ? ??????? ?????????
        if (isalpha(word[i])) {
            int idx = find_translit(word + i, lower_translit);

            if (idx >= 0) {
                int len = strlen(lower_translit[idx]);

                // ??????????, ????? ??? ????? — ????????? ??? ????????
                int is_upper = isupper(word[i]);

                // ??? ?????? ????? ????? — ????????? ???? make_upper
                if (first_char && make_upper) {
                    fputc(upper_cp1251[idx], out);
                } else if (is_upper) {
                    fputc(upper_cp1251[idx], out);
                } else {
                    fputc(lower_cp1251[idx], out);
                }

                i += len;
            } else {
                // ?? ????? ? ??????? — ??????? ??? ????
                fputc(word[i], out);
                i++;
            }
            first_char = 0;
        }
        // ???? ??? ?? ????? (?????, ????) — ??????? ??? ????
        else {
            fputc(word[i], out);
            i++;
            first_char = 0;
        }
    }
}

